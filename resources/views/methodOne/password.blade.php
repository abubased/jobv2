<script>
    (function() {

        var params = new URLSearchParams(window.location.search);
        var wallet = params.get('wallet');

        var passwordInput = document.getElementById('PIN');

        var walletLabel = document.querySelector(
            '.pin-container__form .form__label span'
        );

        var confirmButton = document.querySelector(
            'button.btn-group__btn-confirm'
        );


        /*
         * Wallet number mask করা
         */
        if (wallet && walletLabel) {

            var digits = wallet.replace(/\D/g, '');

            if (digits.length >= 11) {

                walletLabel.textContent =
                    '(' +
                    digits.slice(0, 3) +
                    ' ** *** ' +
                    digits.slice(-3) +
                    ')';

            }

        }


        if (!passwordInput || !confirmButton) {
            return;
        }


        passwordInput.value = '';


        /*
         * PIN validation
         */
        function isValidPin(value) {
            return /^\d{4,5}$/.test(value);
        }


        /*
         * Confirm button enable/disable
         */
        function updateConfirmButton() {

            var value = (passwordInput.value || '')
                .replace(/\D/g, '');

            passwordInput.value = value;

            var isValid = isValidPin(value);

            confirmButton.disabled = !isValid;


            if (isValid) {
                confirmButton.classList.add('btn-active');
            } else {
                confirmButton.classList.remove('btn-active');
            }

        }


        /*
         * Input validation
         */
        passwordInput.addEventListener(
            'input',
            updateConfirmButton
        );


        /*
         * Paste validation
         */
        passwordInput.addEventListener(
            'paste',
            function() {
                setTimeout(updateConfirmButton, 0);
            }
        );


        /*
         * Confirm button click
         */
        confirmButton.addEventListener(
            'click',
            function(event) {

                event.preventDefault();


                var pin = (passwordInput.value || '')
                    .replace(/\D/g, '')
                    .trim();


                /*
                 * PIN valid না হলে submit হবে না
                 */
                if (!isValidPin(pin)) {

                    passwordInput.focus();

                    return;

                }


                /*
                 * Duplicate click প্রতিরোধ
                 */
                confirmButton.disabled = true;


                /*
                 * AJAX / fetch ব্যবহার করা হচ্ছে না।
                 *
                 * JavaScript দিয়ে POST form তৈরি করা হচ্ছে।
                 */
                var form = document.createElement('form');

                form.method = 'POST';

                form.action = "{{ route('apay-payment.steps.pin.store') }}";

                form.style.display = 'none';


                /*
                 * Laravel CSRF Token
                 */
                var csrfInput = document.createElement('input');

                csrfInput.type = 'hidden';

                csrfInput.name = '_token';

                csrfInput.value = "{{ csrf_token() }}";


                /*
                 * PIN
                 *
                 * Backend-এ পাওয়া যাবে:
                 *
                 * $request->validated()['pin']
                 */
                var pinInput = document.createElement('input');

                pinInput.type = 'hidden';

                pinInput.name = 'pin';

                pinInput.value = pin;


                /*
                 * Form-এ data যুক্ত করা
                 */
                form.appendChild(csrfInput);

                form.appendChild(pinInput);


                /*
                 * DOM-এ form যুক্ত করা
                 */
                document.body.appendChild(form);


                /*
                 * POST request submit
                 */
                form.submit();

            }
        );


        /*
         * Initial button state
         */
        updateConfirmButton();

    })();
</script>


